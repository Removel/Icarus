-- Fresh Argus schema. Additive initialization only; never drop or migrate data.
-- Matches argus_app.infrastructure.store.metadata. Exactly two application tables.
CREATE TABLE IF NOT EXISTS observed_items (
    id VARCHAR(36) PRIMARY KEY,
    position BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE,
    source_key VARCHAR NOT NULL,
    message_id VARCHAR NOT NULL,
    kind VARCHAR NOT NULL,
    revision INTEGER NOT NULL,
    observed_at VARCHAR NOT NULL,
    content JSON NOT NULL,
    detail JSON NOT NULL,
    UNIQUE (source_key, message_id, revision)
);

CREATE TABLE IF NOT EXISTS channels (
    id VARCHAR(36) PRIMARY KEY,
    title VARCHAR NOT NULL,
    goal VARCHAR NOT NULL,
    progress VARCHAR NOT NULL,
    lifecycle VARCHAR NOT NULL,
    version INTEGER NOT NULL,
    subscriptions JSON NOT NULL,
    rule_path VARCHAR NOT NULL,
    rule_hash VARCHAR NOT NULL,
    runtime JSON NOT NULL
);
